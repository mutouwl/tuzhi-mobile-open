// Code128（B 码集）条码生成：把票号转成一串「条 / 空」宽度，页面用一排 flex 子项渲染
// （不用 canvas：小程序/H5 的旧版 canvas 链路在导出与绘制回调上差异大，纯 view 渲染两端一致，
//   票码是静态图、不需要导出图片）。
//
// 用法：const bars = code128Bars('12345678901234')  // [{ w: 2, on: true }, { w: 1, on: false }, ...]
//   w   该段宽度（模块数，1~4）
//   on  true = 黑条，false = 空
// 渲染时容器 display:flex，子项 flex-basis:0 + flex-grow:w，条宽按比例铺满容器宽度。
//
// 编码规则（Code128 规范）：
//   起始符 Code B = 104；每个字符值 = ASCII - 32（只支持可打印 ASCII 32~126，票号是数字必然可用）；
//   校验位 = (起始符 + Σ(字符值 × 位序)) % 103；结束符 = 106（7 段 13 模块）。
const CODE128_PATTERNS = [
  '212222', '222122', '222221', '121223', '121322', '131222', '122213', '122312', '132212', '221213',
  '221312', '231212', '112232', '122132', '122231', '113222', '123122', '123221', '223211', '221132',
  '221231', '213212', '223112', '312131', '311222', '321122', '321221', '312212', '322112', '322211',
  '212123', '212321', '232121', '111323', '131123', '131321', '112313', '132113', '132311', '211313',
  '231113', '231311', '112133', '112331', '132131', '113123', '113321', '133121', '313121', '211331',
  '231131', '213113', '213311', '213131', '311123', '311321', '331121', '312113', '312311', '332111',
  '314111', '221411', '431111', '111224', '111422', '121124', '121421', '141122', '141221', '112214',
  '112412', '122114', '122411', '142112', '142211', '241211', '221114', '413111', '241112', '134111',
  '111242', '121142', '121241', '114212', '124112', '124211', '411212', '421112', '421211', '212141',
  '214121', '412121', '111143', '111341', '131141', '114113', '114311', '411113', '411311', '113141',
  '114131', '311141', '411131', '211412', '211214', '211232', '2331112'
];

const START_CODE_B = 104;
const STOP_CODE = 106;

/**
 * 生成 Code128B 条码段
 * @param {String|Number} text 票号等可打印 ASCII 串
 * @return {Array<{w:Number,on:Boolean}>} 空数组表示无法编码（空串 / 有非 ASCII 字符）
 */
export function code128Bars(text) {
  const str = String(text == null ? '' : text);
  if (!str) return [];

  const values = [START_CODE_B];
  let checksum = START_CODE_B;
  for (let i = 0; i < str.length; i++) {
    const code = str.charCodeAt(i);
    if (code < 32 || code > 126) return [];
    const value = code - 32;
    values.push(value);
    checksum += value * (i + 1);
  }
  values.push(checksum % 103, STOP_CODE);

  const bars = [];
  for (let i = 0; i < values.length; i++) {
    const pattern = CODE128_PATTERNS[values[i]];
    if (!pattern) return [];
    for (let k = 0; k < pattern.length; k++) {
      // 每段宽度交替「条、空、条…」，从条开始
      bars.push({ w: Number(pattern[k]), on: k % 2 === 0 });
    }
  }
  return bars;
}
