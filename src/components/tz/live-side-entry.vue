const ENTRY_HEIGHT = 38.25; // 就一个圆底 = 38.25。原来那行 10px 文字 2026-10-01 由用户点名去掉，
// 「圆底 + 间隙 4 + 文字行高 14」那一档随之作废，入口自身高收成圆底直径这一份；
// 尺寸史：48 → 34（2026-10-01「跟底部的带货、送礼物按钮同步一下」）→ 42.5 → **38.25**
// （2026-10-04 同一天两轮：先「再增大1/4」＝×1.25，再「有点太大了，把放大的量缩小1/2」＝减掉增量的一半）。
// ⚠️ 这一条与底部工具条的 34 不再同源，是用户自己给的倍数，不是不齐 —— 要再调就照他下一句改这一个数，
// 圆底两处宽高与图标两处宽高一起改
const ENTRY_GAP = 10;
// 相邻两枚之间的空隙。原先步进就是 ENTRY_HEIGHT，两枚贴死、中间没缝，看着是一整条糊在一起的竖条
// （2026-09-30 用户点名「上下之间是没有间距的，看起来不太协调，增加一些间距」）。10 这一档与本组件
// `right: 10px` 的横向内衬对齐；相邻档 6 / 10 / 14。**2026-10-04 圆底放大/收回时这一档始终没跟着放大**
//（用户点名的是按钮本身），要同比放大给 12.5（步进 50.75）。
const ENTRY_STEP = ENTRY_HEIGHT + ENTRY_GAP;

export default {
	name: 'tz-live-side-entry',
	props: {
		icon: { type: String, default: '' },
		iconName: { type: String, default: '' },
		top: { type: String, default: '38%' },
		/** 讨论区垂直中心线（px，相对直播间容器顶边）。> 0 时整栏按它居中，忽略 top */
		centerY: { type: [Number, String], default: 0 },
		/** 参与居中的常驻枚数（不含晚到的消息入口）。只决定整栏的基准线，不参与发号 */
		stackCount: { type: [Number, String], default: 0 },
		level: { type: [Number, String], default: 0 },
	},
	emits: ['open'],
	computed: {
		posStyle() {
			// 基准线：给了讨论区中心线就按「整栏居中」算，没给（首帧还没量到）才退回 top 那一档
			let base = this.top;
			const center = Number(this.centerY) || 0;
			if (center > 0) {
				const n = Math.max(0, Number(this.stackCount) || 0);
				// 整栏高度 = 枚数 × 自身高 + (枚数 − 1) × 间距；栏高的一半从中心线上减去即最上那枚的顶边
				const stackHeight = n > 0 ? n * ENTRY_HEIGHT + (n - 1) * ENTRY_GAP : 0;
				base = center - stackHeight / 2 + 'px';
			}
			const offset = (Number(this.level) || 0) * ENTRY_STEP;
			if (!offset) {
				return 'top: ' + base;
			}
			// 自上而下发号：level 0 = 锚点那一枚（最上），正数往下让一格。
			// 用 calc 而不是换算成 px：centerY 没给时 top 可能是 38% 这一档，要跟着容器高度走
			// （负数 = 锚点之上那一档，本栏没用到，组件按同一条轴对称支持）
			//
			// ⚠️ calc() 里的 + 与 - 两侧必须各留一个空格（CSS 语法硬要求）。紧凑写法（38% +76px）
			// 整条 top 会被判非法直接丢掉，那一枚便落回静态位置 = 容器右上角，症状是「这一枚跑到页面
			// 右上角去了、整栏不齐」（2026-09-30 用户点名「邀请达人榜和这个消息按钮全部跑在页面的右上角」）。
			// 符号要连空格一起当字面量给（' + ' / ' - '），拆成 ' ' + 符号 或 符号 + 数字 拼出来就是非法值，
			// 而源码上看着完全正常。验法：node tuzi-mobile/scripts/check-side-entry-style.js
			// （跑真实的 posStyle 逐层验），手写紧凑写法另有 node tools/ui-audit.js --pattern calc-operator-no-space。
			return 'top: calc(' + base + (offset > 0 ? ' + ' : ' - ') + Math.abs(offset) + 'px)';
		},
	},
};
</script>

